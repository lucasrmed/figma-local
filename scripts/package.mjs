#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, basename } from 'node:path';
import { createHash } from 'node:crypto';
import { APP_ROOT } from '../platform.mjs';
import { packageFiles } from './files.mjs';
import { parseArgs } from 'node:util';
const { values } = parseArgs({ options: { target: { type: 'string' } } });
const target = values.target || (process.platform === 'win32' ? 'windows' : 'macos');
if (!['macos', 'windows'].includes(target)) throw Error('Destino: macos ou windows.');
const pkg = JSON.parse(readFileSync(join(APP_ROOT, 'package.json'), 'utf8'));
if (!/^\d+\.\d+\.\d+(?:-[A-Za-z0-9.-]+)?$/.test(pkg.version)) throw Error('Versão inválida para distribuição.');
const destination = join(APP_ROOT, 'dist', `figma-local-${target}-${pkg.version}.zip`);
mkdirSync(join(APP_ROOT, 'dist'), { recursive: true });
const files = packageFiles(APP_ROOT);
for (const file of files) if (!statSync(join(APP_ROOT, file)).isFile()) throw Error('Pacote contém entrada inválida.');
const python = `import json,sys,zipfile,pathlib\np=json.load(sys.stdin)\nwith zipfile.ZipFile(p['destination'],'w',zipfile.ZIP_DEFLATED) as z:\n for f in p['files']:\n  data=(pathlib.Path(p['root'])/f).read_bytes()\n  if f.endswith('.cmd'): data=data.replace(b'\\r\\n',b'\\n').replace(b'\\n',b'\\r\\n')\n  info=zipfile.ZipInfo('FigmaLocal/'+f)\n  info.create_system=3\n  info.external_attr=(0o100755 if f.endswith('.command') else 0o100644)<<16\n  info.compress_type=zipfile.ZIP_DEFLATED\n  z.writestr(info,data)\n`;
execFileSync(process.platform === 'win32' ? 'python' : 'python3', ['-c', python], { input: JSON.stringify({ root: APP_ROOT, destination, files }), encoding: 'utf8' });
const hash = createHash('sha256').update(readFileSync(destination)).digest('hex');
writeFileSync(join(APP_ROOT, 'dist', 'SHA256SUMS'), `${hash}  ${basename(destination)}\n`);
console.log(JSON.stringify({ archive: destination, target, files: files.length, bytes: statSync(destination).size, includesDesignData: false, includesBrowserProfile: false }));
